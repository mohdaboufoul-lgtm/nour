"""The alembic chain equals the models (DESIGN §5.3, §7.3 ``tests/unit/test_migrations_match_metadata.py``):
``alembic upgrade head`` on a temp SQLite file produces a schema whose autogenerate diff against
``Base.metadata`` is empty, carries exactly the triggers ``create_schema`` installs, downgrades
cleanly, and the revision file freezes the wall markers and the per-role grants without importing
the models. The offline (``--sql``) script is Postgres-only and carries the roles, grants, RLS
policies and partial indexes.
"""

