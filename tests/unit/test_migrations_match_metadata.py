PG_URL = os.environ.get("NOUR_DATABASE_URL", "")


@pytest.mark.postgres
@pytest.mark.skipif(not PG_URL.startswith("postgresql"), reason="NOUR_DATABASE_URL is not Postgres")
def test_postgres_upgrade_head_yields_an_empty_diff_with_schemas() -> None:
    engine = make_engine(PG_URL)
    try:
        Base.metadata.drop_all(engine)
        with engine.begin() as connection:
            connection.exec_driver_sql("DROP TABLE IF EXISTS alembic_version")
        command.upgrade(_config(PG_URL), "head")
        with engine.connect() as connection:
            context = MigrationContext.configure(
                connection,
                opts={
                    "compare_type": True,
                    "compare_server_default": True,
                    "include_schemas": True,
                },
            )
            diff = compare_metadata(context, metadata_for_dialect("postgresql"))
            # alembic does not compare postgresql_where: prove the predicates were created
            indexdefs: dict[str, str] = {
                name: definition
                for name, definition in connection.exec_driver_sql(
                    "SELECT indexname, indexdef FROM pg_indexes WHERE indexname IN "
                    "('ix_approval_decision', 'ix_freeze_state_released_at', "
                    "'ix_pending_owner_message_sent_at')"
                ).all()
            }
        assert diff == [], diff
        assert set(indexdefs) == {
            "ix_approval_decision",
            "ix_freeze_state_released_at",
            "ix_pending_owner_message_sent_at",
        }
        assert all(
            "WHERE" in definition and "IS NULL" in definition for definition in indexdefs.values()
        )
    finally:
        engine.dispose()
